const assert = require('assert');
const fs = require('fs');
const scheduler = require('../utils/scheduler');
const { DAY_MS, startOfDay } = require('../utils/date');
const model = require('../utils/sync-model');
const plan = require('../utils/study-plan');
const now = new Date(2026, 9, 29, 12).getTime();
const clone = value => JSON.parse(JSON.stringify(value));

const legacy = { seen: true, reps: 8, lapses: 2, interval: 30, dueAt: now, recoveredAt: now - DAY_MS, custom: 'keep' };
const before = clone(legacy);
const first = scheduler.review(legacy, 'good', now);
assert.deepStrictEqual(legacy, before, 'gradual entry never rewrites its source history');
assert.equal(first.reps, 9);
assert.equal(first.recoveredAt, legacy.recoveredAt);
assert.equal(first.custom, 'keep');
assert.equal(first.fsrs.reps, 1, 'legacy reps are not fabricated model observations');
assert.equal(first.fsrs.stability, 2.3065, 'locked upstream FSRS-6 default parameter');
assert.equal(first.interval, 2);
assert.equal(first.fsrsVersion, 'FSRS-6/ts-fsrs-5.4.1');
const onTime = scheduler.review(clone(first), 'good', now + 2 * DAY_MS);
const late = scheduler.review(clone(first), 'good', now + 20 * DAY_MS);
assert.ok(late.interval > onTime.interval, 'a late successful recall supplies different evidence from an on-time success');
const partial = scheduler.review(clone(first), 'hard', now + 2 * DAY_MS);
const failed = scheduler.review(clone(first), 'again', now + 2 * DAY_MS);
assert.equal(partial.fsrs.stability, failed.fsrs.stability, 'partial main-sense recall is a failing model grade');
assert.ok(partial.needsRecall);
const passedToday = scheduler.review(partial, 'good', now + 2 * DAY_MS + 10000);
assert.ok(passedToday.dueAt <= startOfDay(now + 2 * DAY_MS) + DAY_MS, 'same-day recovery does not erase the earlier failure');
assert.deepStrictEqual(scheduler.review(passedToday, 'easy', now + 2 * DAY_MS + 20000).fsrs, passedToday.fsrs, 'repeat success is not another spaced success');
const bundle = { state: { cards: { x: first }, daily: {}, weakBook: {}, recentReviews: [] } };
const other = clone(bundle);
model.apply(other, { device: 'other-device', seq: 1, baseRev: 0, changes: [{ path: ['state','cards','x'], before: legacy, after: late }] });
assert.equal(other.state.cards.x.fsrs, null, 'concurrent memory states must not be spliced');
assert.ok(other.state.cards.x.needsRecall && other.state.cards.x.fsrsNeedsRecheck);
assert.ok(scheduler.review(other.state.cards.x, 'good', now + 21 * DAY_MS).fsrs, 'a real answer can safely re-enter after conflict');
const deadline = { learningDeadline: '2026-12-18' }, word = { position: 0 };
assert.equal(plan.examCoverageDue(word, { seen:true, reps:1, passedDay:'2026-10-01' }, deadline, new Date('2026-11-20T12:00:00+08:00').getTime()), false);
assert.equal(plan.examCoverageDue(word, { seen:true, reps:1, passedDay:'2026-10-01' }, deadline, new Date('2026-11-21T12:00:00+08:00').getTime()), true);
assert.equal(plan.examCoverageDue(word, { seen:true, reps:1, passedDay:'2026-11-21' }, deadline, new Date('2026-12-18T12:00:00+08:00').getTime()), false);
assert.equal(plan.examCoverageDue(word, { seen:true, reps:1 }, deadline, new Date('2026-12-19T12:00:00+08:00').getTime()), false);

const values = { mem_vocab_state_v1: { schemaVersion:3, cards:{}, daily:{}, weakBook:{}, recentReviews:[] }, mem_vocab_settings_v1: { schemaVersion:2, reviewLimitVersion:1, examPlanVersion:1 } };
let sessionOptions, player;
global.wx = { getStorageSync:key=>clone(values[key] || ''), setStorageSync:(key,value)=>{values[key]=clone(value);}, removeStorageSync:key=>{delete values[key];},
  setInnerAudioOption(options) { sessionOptions = options; options.success(); },
  createInnerAudioContext() { player={ onError(){}, play(){}, stop(){}, destroy(){} }; return player; }, showToast(){}, navigateBack(){} };
const audio = require('../utils/audio-options').create();
assert.equal(sessionOptions.obeyMuteSwitch, false, 'configure global iOS audio session');
assert.equal(audio.obeyMuteSwitch, false);
assert.equal(audio.volume, 1);
const store = require('../utils/store');
values.mem_vocab_settings_v1 = { schemaVersion: 1, dailyReviewLimit: 80, examDate: '2026-11-07' };
store.ensureState();
assert.equal(store.getSettings().examDate, '2026-12-19');
assert.equal(store.getSettings().learningDeadline, '2026-12-18');
assert.equal(require('../utils/sync-storage').read('mem_vocab_before_fsrs_v1').settings.dailyReviewLimit, 80, 'snapshot predates all settings migrations');
const large = clone(values.mem_vocab_state_v1);
large.safety = 'large archive'.repeat(120000);
store.saveState(large);
assert.equal(values.mem_vocab_state_v1.syncChunks, 1, 'large FSRS archives use durable chunks');
assert.equal(store.getState().safety, large.safety);
const manifest = clone(values.mem_vocab_state_v1); delete values[manifest.prefix + ':0'];
assert.throws(()=>store.getState(), /incomplete-sync-storage/, 'a broken chunk must never initialize empty progress');
assert.deepStrictEqual(values.mem_vocab_state_v1, manifest);
store.saveState({ schemaVersion:3, cards:{}, daily:{}, weakBook:{}, recentReviews:[] });
const stateBefore = JSON.stringify(store.getState());
let page;
global.Page = definition => {page = definition;};
require('../word-detail/index');
page.setData = patch => Object.assign(page.data, patch);
page.onLoad({ id:'c-1-1' });
assert.equal(JSON.stringify(store.getState()), stateBefore, 'opening word details cannot grade or alter learning state');
assert.equal(store.getSession(), null);
page.onUnload();
const study = fs.readFileSync(require.resolve('../pages/study/index.wxml'), 'utf8');
const detail = fs.readFileSync(require.resolve('../word-detail/index.wxml'), 'utf8');
assert.ok(study.includes('<word-card') && detail.includes('<word-card'), 'learning and details share the same content component');
assert.ok(!detail.includes('data-grade') && !detail.includes('openRelations') && !fs.readFileSync(require.resolve('../components/word-card/index.wxml'), 'utf8').includes('relation-trigger'), 'details have neither grading nor recursive relations');
const relation = fs.readFileSync(require.resolve('../components/word-relations/index.wxml'), 'utf8');
assert.ok(!relation.includes('继续关联'));
assert.ok(relation.includes('catchtap="close"') && relation.indexOf('</view></view>') < relation.indexOf('class="sheet-head"'), 'the close control is outside the drag-capture container');
console.log('FSRS reference values, actual spacing, conservative rating, old progress, conflict recheck, exam coverage, audio session, large archive integrity and shared read-only details passed.');
