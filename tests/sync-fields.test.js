const assert = require('assert');
const model = require('../utils/sync-model'), budget = require('../utils/sync-budget');
const clone = model.clone, day = '2026-11-03', device = 'field-test-owner';
const before = { state: { schemaVersion: 3, cards: {}, weakBook: {}, sentenceBook: {}, recentReviews: [], daily: { [day]: {
  dueDone: 0, newDone: 0, backlogDone: 0, dueGoal: 100, newGoal: 50,
  taskPlan: Object.fromEntries(Array.from({ length: 150 }, (_, i) => ['word-' + i, 'review'])),
  taskStatus: Object.fromEntries(Array.from({ length: 150 }, (_, i) => ['word-' + i, { at: 1, passed: false }])),
  time: { version: 1, legacySeconds: 0, segments: Object.fromEntries(Array.from({ length: 500 }, (_, i) => ['span-' + i, { start: i * 30000, end: i * 30000 + 20000, phase: 'review' }])) },
} } }, settings: { schemaVersion: 2 }, session: { day, startedAt: 100, index: 5, queue: Array.from({ length: 400 }, (_, i) => ({ wordId: 'word-' + i, phase: 'review' })) }, practiceSession: null };
const after = clone(before);
after.state.daily[day].time.segments['span-499'].end += 30000;
let changes = model.fineDiff(before, after);
assert.strictEqual(changes.length, 1);
assert.strictEqual(changes[0].path.join('/'), `state/daily/${day}/time/segments/span-499`);
assert.ok(Buffer.byteLength(JSON.stringify(changes)) < 400, '30 seconds must not transmit the whole day or task queue');
const event = changes => ({ device, seq: 1, epoch: 1, baseRev: 1, changes });
const owner = { owner: { device, epoch: 1 } };
const applied = clone(before); model.apply(applied, event(changes), owner);
assert.deepStrictEqual(applied, after);
const concurrent = clone(before);
concurrent.state.daily[day].time.segments['other-device'] = { start: 99999999, end: 999999999, phase: 'detail' };
model.apply(concurrent, event(changes), owner);
assert.ok(concurrent.state.daily[day].time.segments['other-device']);
assert.strictEqual(Object.keys(concurrent.state.daily[day].time.segments).length, 501);
const later = clone(after); later.state.daily[day].time.segments['span-499'].end += 30000;
model.apply(later, event(changes), owner);
assert.strictEqual(later.state.daily[day].time.segments['span-499'].end, after.state.daily[day].time.segments['span-499'].end + 30000, 'a delayed interval cannot shorten time');
const progress = clone(after); progress.session.index++;
changes = model.fineDiff(after, progress);
assert.ok(JSON.stringify(changes).length < 100, 'moving forward sends an index, not 400 queued questions');
const queued = clone(progress); queued.session.queue.splice(20, 0, { wordId: 'extra-word', phase: 'reinforcement' }); queued.session.index++;
changes = model.fineDiff(progress, queued);
assert.ok(JSON.stringify(changes).length < 500, 'inserting one question sends only the inserted item and queue base fingerprints');
const patched = clone(progress); model.apply(patched, event(changes), owner); model.apply(patched, event(changes), owner);
assert.deepStrictEqual(patched, queued, 'queue splice is idempotent');
assert.deepStrictEqual(model.overlay(clone(progress), changes), queued, 'the authoritative queue delta can be overlaid');
const delta = require('../cloudfunctions/lexiloop-sync/delta');
const queuedAgain = clone(queued); queuedAgain.session.queue.splice(21, 0, { wordId: 'another-extra', phase: 'sentence' }); queuedAgain.session.index++;
const record = { rev: 6, bundle: queuedAgain };
delta.recordDelta(record, progress, 5, [{ changes }, { changes: model.fineDiff(queued, queuedAgain) }]);
const response = delta.since(record, 5, 2);
assert.ok(!response.changes.some(c => c.path[0] === 'session' && c.path.length === 1), 'two accepted queue edits in one batch do not force a full task echo');
assert.deepStrictEqual(model.overlay(clone(progress), response.changes), queuedAgain);
const legacyResponse = delta.since(record, 5, 1);
assert.ok(legacyResponse.changes.every(c => c.path[0] !== 'session' || c.path.length === 1), 'old clients receive only task roots they understand');
assert.deepStrictEqual(model.overlay(clone(progress), legacyResponse.changes), queuedAgain);
const alien = clone(progress); alien.session.queue.pop();
const oldIndex = alien.session.index;
model.apply(alien, event(changes.concat({ path: ['state', 'recentReviews'], append: [{ id: 'real-answer', wordId: 'extra-word', at: 1 }] })), owner);
assert.strictEqual(alien.session.index, oldIndex, 'a queue-base conflict rejects associated cursor changes');
assert.strictEqual(alien.state.recentReviews.length, 1, 'a task conflict never discards an independent answer');
const wrongOwner = clone(progress); model.apply(wrongOwner, event(changes), { owner: { device: 'other-owner', epoch: 2 } });
assert.deepStrictEqual(wrongOwner, progress, 'nested task changes obey ownership too');
const status = clone(before); status.state.daily[day].taskStatus['word-0'] = { at: 200, passed: false };
model.apply(status, event([{ path: ['state', 'daily', day, 'taskStatus', 'word-0'], before: { at: 1, passed: false }, after: { at: 100, passed: true } }]), owner);
assert.strictEqual(status.state.daily[day].taskStatus['word-0'].at, 200);
assert.throws(() => model.apply(clone(before), event([{ path: ['state', 'daily', day, 'time', 'segments', '__proto__'], after: {} }]), owner), /invalid-path/);
assert.throws(() => model.apply(clone(before), event([{ path: ['session', 'queue'], splice: { start: -1 } }]), owner), /invalid-queue-patch/);
const oldChanges = model.diff(before, after);
assert.deepStrictEqual(model.fineChanges(oldChanges), model.fineDiff(before, after), 'pending legacy daily snapshots can migrate without inventing answers');
const meta = {}, at = Date.parse('2026-11-03T10:00:00+08:00');
for (let i = 0; i < budget.MAX_CALLS; i++) budget.reserve(meta, 'sync', at);
const durable = clone(meta);
assert.throws(() => budget.reserve(durable, 'sync', at + 60000), error => error.code === 'SYNC_DAILY_BUDGET', 'restarting cannot reset the local request fuse');
budget.reserve(durable, 'sync', Date.parse('2026-11-04T00:00:00+08:00'));
assert.strictEqual(durable.requestBudget.calls, 1);
const chunks = {};
for (let i = 0; i < 250; i++) budget.reserve(chunks, 'wire-put', at);
assert.throws(() => budget.reserve(chunks, 'wire-put', at), error => error.code === 'SYNC_DAILY_BUDGET', 'internal chunk work consumes the weighted budget too');
const events = Array.from({ length: 60 }, (_, seq) => ({ seq: seq + 1, changes: [{ path: ['state', 'weakBook', 'x'], after: 'x'.repeat(1000) }] }));
assert.ok(budget.batch(events).length < 20);
assert.deepStrictEqual(budget.batch(events).map(e => e.seq), events.slice(0, budget.batch(events).length).map(e => e.seq), 'bounded batches preserve contiguous event order');
console.log('Field sync passed: bounded timing/cursor/question deltas, replay, conflicts, ownership, migration and durable daily request budgets.');
