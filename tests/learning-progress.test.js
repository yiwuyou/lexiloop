const assert = require('assert');
const { getWords } = require('../utils/words');
const metrics = require('../utils/learning-metrics');
const spacing = require('../utils/question-order');
const plan = require('../utils/study-plan');
const clone = value => JSON.parse(JSON.stringify(value));
const day = '2026-10-31', now = Date.parse(day + 'T11:29:18+08:00');
const words = getWords(), old = words.slice(0, 100), fresh = words.slice(100, 150);
const taskPlan = Object.fromEntries(old.map(w => [w.id, 'review']).concat(fresh.map(w => [w.id, 'new'])));
const state = { cards: {}, daily: { [day]: { dueGoal: 100, newGoal: 50, dueDone: 10, newDone: 0, taskPlan, firstAnswers: Object.fromEntries(old.slice(0, 10).map(w => [w.id, 'review'])) } }, recentReviews: [] };
old.forEach((word, i) => { state.cards[word.id] = { seen: true, passedDay: i < 5 ? day : '', needsRecall: i >= 5 && i < 10 }; });
const prefix = old.slice(0, 10).map(w => ({ wordId: w.id, phase: 'review' })).concat(old.slice(0, 10).map(w => ({ wordId: w.id, phase: 'reinforcement' })));
const session = { day, index: 20, dueGoal: 100, newGoal: 50, dueDone: 10, newDone: 0,
 queue: prefix.concat(old.slice(5, 10).map(w => ({ wordId: w.id, phase: 'reinforcement' })), old.slice(10).map(w => ({ wordId: w.id, phase: 'review' })), old.slice(0, 10).map(w => ({ wordId: w.id, phase: 'sentence', questionId: 'original-' + w.id })), fresh.map(w => ({ wordId: w.id, phase: 'new' }))) };
const initial = metrics.summary(state, session, day);
assert.strictEqual(initial.reviewSeen, 10, 'ten distinct reviewed words must not display as zero or twenty');
assert.strictEqual(initial.reviewPercent, 10);
assert.strictEqual(initial.reviewPassed, 0, 'do not pretend unfinished questions are completed');
assert.strictEqual(initial.reviewPending, 10);
assert.strictEqual(initial.reviewUnseen, 90);
assert.strictEqual(initial.newSeen, 0);
assert.strictEqual(metrics.section(initial, 'review').verb, '已复习');
const cardsBefore = JSON.stringify(state.cards), prefixBefore = JSON.stringify(prefix);
assert.strictEqual(spacing.prepare(session, state), true);
assert.strictEqual(JSON.stringify(session.queue.slice(0, 20)), prefixBefore);
assert.strictEqual(JSON.stringify(state.cards), cardsBefore);
const questionPositions = session.queue.map((item, i) => item.phase === 'sentence' ? i : -1).filter(i => i >= 0);
assert.strictEqual(questionPositions.length, 10, 'preserve every original unfinished question');
assert.ok(questionPositions[0] < session.queue.findLastIndex(item => item.phase === 'review'), 'questions must be interleaved rather than all appended after reviews');
assert.ok(questionPositions.every(i => session.queue[i].questionId.startsWith('original-')));
assert.strictEqual(spacing.prepare(session, state), false, 'reopening must not keep moving the questions farther away');
state.recentReviews.push({ day, at: now, wordId: old[10].id, phase: 'review', result: 'again' });
assert.strictEqual(metrics.summary(state, session, day).reviewSeen, 11, 'an unsuccessful real review is still work done');
state.recentReviews.push({ day, at: now + 1, wordId: old[0].id, phase: 'reinforcement', result: 'good' }, { day, at: now + 2, wordId: old[0].id, phase: 'sentence', result: 'correct' });
assert.strictEqual(metrics.summary(state, session, day).reviewSeen, 11, 'retries and choices do not add distinct words');
const singleState = { cards: { [old[0].id]: { seen: true, passedDay: day } }, daily: { [day]: { taskPlan: { [old[0].id]: 'review' }, firstAnswers: { [old[0].id]: 'review' } } }, recentReviews: [] };
const onlyQuestions = { day, index: 1, queue: [{ wordId: old[0].id, phase: 'review' }, { wordId: old[0].id, phase: 'sentence', questionId: 'remaining-example' }] };
spacing.prepare(onlyQuestions, singleState);
assert.strictEqual(onlyQuestions.queue.length, 2, 'if only an example remains, preserve it without making the user repeat a completed recall');
const yesterday = clone(singleState);yesterday.cards[old[0].id].passedDay = '2026-10-30';yesterday.daily = {};
const carried = { day, index: 0, queue: [{ wordId: old[0].id, phase: 'sentence', questionId: 'carried-example' }] };
spacing.prepare(carried, yesterday);
assert.strictEqual(carried.queue[0].phase, 'review', 'an example alone cannot replace a real recall today');
assert.strictEqual(carried.queue[1].questionId, 'carried-example');
const generated = { day, index: 0, queue: old.slice(0, 20).map(w => ({ wordId: w.id, phase: 'review' })) };
assert.strictEqual(plan.queueContextCheck(generated, old[0], 'hard', now), true);
const generatedPosition = generated.queue.findIndex(item => item.phase === 'sentence');
assert.ok(generatedPosition >= 8 && generatedPosition < 20, 'new questions leave intervening work and are not pushed to the end');
console.log('Visible reviewed/learned words, pending follow-ups, failed grades, deduplication, original-question spacing and resume/carry safeguards passed.');
